/*
 * Adaptive frequency-domain demosaicking for Fujifilm X-Trans sensors.
 *
 * Primary references:
 *   M. Rafinazari and E. Dubois, "Demosaicking Algorithm for the
 *   Fujifilm X-Trans Color Filter Array", ICIP 2014, pp. 660-663.
 *   https://doi.org/10.1109/ICIP.2014.7025132
 *
 *   M. Rafi Nazari, "Denoising and Demosaicking of Color Images",
 *   PhD dissertation, University of Ottawa, 2017, section 3.3,
 *   "Demosaicking for the Fujifilm X-Trans pattern", pp. 33-48.
 *   https://ruor.uottawa.ca/items/036d51e5-a089-456a-8e8c-c4a009338f41
 *
 * The references describe Gaussian band-pass filters in the frequency
 * domain. This implementation applies the equivalent finite-support,
 * modulated, separable Gaussian kernels in the spatial domain. It is an
 * independent reconstruction, not source code supplied by the authors.
 * Filter supports and several adaptive-energy parameters are not published;
 * the corresponding choices are documented below and exposed as experimental
 * controls.
 */

