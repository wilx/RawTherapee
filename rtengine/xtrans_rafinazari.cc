bool RawImageSource::rafinazari_xtrans_interpolate(const procparams::RAWParams::XTransSensor& params)
{
    int xtrans[6][6];
    ri->getXtransMatrix(xtrans);

    Transform transform {};
    if (!findTransform(xtrans, transform)) {
        return false;
    }

    if (plistener) {
        plistener->setProgressStr(Glib::ustring::compose(M("TP_RAW_DMETHOD_PROGRESSBAR"), M("TP_RAW_RAFINAZARIADAPTIVE")));
        plistener->setProgress(0.0);
    }

    const auto clampInt = [](int value, int minimum, int maximum) {
        return std::max(minimum, std::min(maximum, value));
    };
    const auto clampDouble = [](double value, double minimum, double maximum) {
        return std::max(minimum, std::min(maximum, value));
    };
    const double reconstructionSigma = clampDouble(params.rafinazariSigma, 0.5, 5.0);
    const double energySigma = clampDouble(params.rafinazariEnergySigma, 0.5, 5.0);
    const int energyRadius = clampInt(params.rafinazariEnergyRadius, 1, 24);
    const int energyBoxRadius = clampInt(params.rafinazariEnergyBoxRadius, 0, 12);
    const double energyFloor = clampDouble(params.rafinazariEnergyFloor, 0.0, 10.0);
    const int radii[3] = {
        clampInt(params.rafinazariNearRadius, 1, 24),
        clampInt(params.rafinazariMiddleRadius, 1, 24),
        clampInt(params.rafinazariFarRadius, 1, 24)
    };

    std::array<Filter, 12> chromaFilters;
    for (size_t i = 0; i < chromaFilters.size(); ++i) {
        // The three groups are exactly those specified on dissertation p. 37:
        // q2/q3/q10/q11, q6/q7/q12/q13, and q14/q15/q16/q17.
        const int group = (i == 0 || i == 1 || i == 4 || i == 5) ? 0 : (i < 8 ? 1 : 2);
        chromaFilters[i] = makeFilter(mapFrequency(CHROMA_FREQUENCIES[i], transform),
                                      reconstructionSigma, radii[group]);
    }

    // Section 3.3, pp. 39-40 and equations 3.29-3.30: estimate overlap at the
    // midpoint between luma and one representative of each conjugate pair.
    // q2, q6, q10, and q12 drive fC1; q14 and q15 drive fC2.
    constexpr int ENERGY_COMPONENTS[6] = {0, 2, 4, 6, 8, 9};
    std::array<Filter, 6> energyFilters;
    for (size_t i = 0; i < energyFilters.size(); ++i) {
        Frequency midpoint = CHROMA_FREQUENCIES[ENERGY_COMPONENTS[i]];
        midpoint.x *= 0.5;
        midpoint.y *= 0.5;
        energyFilters[i] = makeFilter(mapFrequency(midpoint, transform),
                                      energySigma, energyRadius);
    }

    const int tilesX = (W + TILE_SIZE - 1) / TILE_SIZE;
    const int tilesY = (H + TILE_SIZE - 1) / TILE_SIZE;

#ifdef BENCHMARK
    const char* variant = std::getenv("RT_RAFINAZARI_VARIANT");
    const bool useLiteral = variant && std::string(variant) == "literal";
#endif

#ifdef _OPENMP
    #pragma omp parallel
#endif
    {
        ThreadWorkspace workspace;

#ifdef _OPENMP
        #pragma omp for schedule(dynamic, 1) collapse(2)
#endif
        for (int tileY = 0; tileY < tilesY; ++tileY) {
            for (int tileX = 0; tileX < tilesX; ++tileX) {
                const int x0 = tileX * TILE_SIZE;
                const int y0 = tileY * TILE_SIZE;
                const int tileWidth = std::min(TILE_SIZE, W - x0);
                const int tileHeight = std::min(TILE_SIZE, H - y0);
                const size_t pixelCount = static_cast<size_t>(tileWidth) * tileHeight;

                for (size_t i = 0; i < workspace.components.size(); ++i) {
                    filterTile(rawData, W, H, x0, y0, tileWidth, tileHeight,
                               chromaFilters[i], workspace.horizontal, workspace.components[i]);
                }

                for (size_t i = 0; i < workspace.energies.size(); ++i) {
                    energyTile(rawData, W, H, x0, y0, tileWidth, tileHeight,
                               energyBoxRadius, energyFilters[i], workspace.horizontal,
                               workspace.filtered, workspace.integral, workspace.energies[i]);
                }

                for (size_t index = 0; index < pixelCount; ++index) {
                    std::array<Complex, 12> q;
                    for (size_t i = 0; i < q.size(); ++i) {
                        q[i] = workspace.components[i].data[index];
                    }

                    const std::array<float, 4> c1Energy {{
                        workspace.energies[0].data[index], workspace.energies[1].data[index],
                        workspace.energies[2].data[index], workspace.energies[3].data[index]
                    }};
                    const std::array<float, 2> c2Energy {{
                        workspace.energies[4].data[index], workspace.energies[5].data[index]
                    }};
                    const auto c1Weights = inverseEnergyWeights(c1Energy, energyFloor);
                    const auto c2Weights = inverseEnergyWeights(c2Energy, energyFloor);

                    // Production uses the normalized conjugate-pair equations
                    // 3.47 and 3.49. Equation 3.31 remains benchmark-only.
                    float c1;
#ifdef BENCHMARK
                    c1 = useLiteral ? literalC1(q, c1Weights) : normalizedC1(q, c1Weights);
#else
                    c1 = normalizedC1(q, c1Weights);
#endif
                    const float c2 = normalizedC2(q, c2Weights);

                    const int tx = static_cast<int>(index % tileWidth);
                    const int ty = static_cast<int>(index / tileWidth);
                    const int x = x0 + tx;
                    const int y = y0 + ty;

                    float modulatedChroma = 0.f;
                    for (size_t i = 0; i < q.size(); ++i) {
                        const Complex reconstructed = C1_COEFFICIENTS[i] * c1 + C2_COEFFICIENTS[i] * c2;
                        const Complex modulation = std::conj(chromaFilters[i].demodulation[modulo(y, 12) * 12 + modulo(x, 12)]);
                        modulatedChroma += (reconstructed * modulation).real();
                    }

                    // Dissertation equation 3.50: recover baseband luma by
                    // subtracting all reconstructed modulated chroma carriers
                    // from the CFA signal at the measured sample.
                    const float luma = rawData[y][x] - modulatedChroma;

                    // Dissertation equation 3.51: inverse transform from
                    // (fL, fC1, fC2) to the complete linear RGB estimate.
                    float r = luma - (10.f / 9.f) * c1 - 2.f * c2;
                    float g = luma + (8.f / 9.f) * c1;
                    float b = luma - (10.f / 9.f) * c1 + 2.f * c2;

                    if (!std::isfinite(r) || !std::isfinite(g) || !std::isfinite(b)) {
                        r = g = b = rawData[y][x];
                    }

                    red[y][x] = r;
                    green[y][x] = g;
                    blue[y][x] = b;
                }
            }
        }
    }

    if (plistener) {
        plistener->setProgress(1.0);
    }

    return true;
}

